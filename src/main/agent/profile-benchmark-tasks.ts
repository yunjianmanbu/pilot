  "  console.error('failed to parse data.json:', error.message)",
  '  process.exit(1)',
  '}',
  '',
  'if (!Array.isArray(data.items)) {',
  "  console.error('data.items must be an array')",
  '  process.exit(1)',
  '}',
  '',
  'if (data.items.length !== 3) {',
  "  console.error('expected 3 items, got', data.items.length)",
  '  process.exit(1)',
