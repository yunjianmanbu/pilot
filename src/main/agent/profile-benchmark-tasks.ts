/**
 * Built-in benchmark suite for comparing two profiles.
 *
 * The tasks must be (a) small enough to run twice in a few minutes, (b) graded
 * by an objective check so the verdict does not depend on a judge's taste, and
 * (c) fair to a real agent: every fixture is self-contained and needs no
 * network. Shell access is granted like in production, so a profile may tell
 * the agent to verify its own work with run_shell; the fixtures still pass
 * without it. They deliberately exercise the behaviours a profile is supposed to
 * change — reading before editing, matching the existing style, finishing the
 * stated task instead of a nearby one.
 */
import type { BenchmarkTask } from './profile-benchmark'

const nodeCheck = (script: string): BenchmarkTask['check'] => ({
  command: process.platform === 'win32' ? 'node.exe' : 'node',
  args: ['-e', script],
  timeoutMs: 60_000,
})

/**
 * `check.js` handed to the agent in `fix-broken-json`. The task forbids editing
 * it, so the check compares the file byte-for-byte (line endings normalised)
 * before running it. Keeping the source here means fixture and expectation
 * cannot drift apart.
 */
