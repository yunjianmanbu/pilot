import type { PluginTemplateId } from '../../shared/types'

/**
 * Scaffolding templates for the plugin assistant.
 *
 * Generated entries are deliberately dependency-free Node ESM files: the host
 * runs them as child processes and talks newline-delimited JSON-RPC, so a
 * template only has to stay readable and protocol-correct. The `String.raw`
 * literals below are written exactly as they land on disk, which keeps the
 * generated `'\n'` escapes single.
 */

export interface PluginTemplateRoute {
  method: 'GET' | 'POST' | 'PUT' | 'DELETE'
  path: string
  auth: 'public' | 'required'
  permission: string | null
  description: string
}

export interface PluginTemplate {
  id: PluginTemplateId
  name: string
  summary: string
  /** One line describing the generated behaviour, reused in README. */
  about: string
  permissions: string[]
  provides: 'session' | null
  routes: PluginTemplateRoute[]
  entry: string
}

const PROTOCOL_HELPERS = String.raw`
function reply(id, result) {
  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: id, result: result }) + '\n')
}

function replyError(id, code, message) {
  process.stdout.write(
    JSON.stringify({ jsonrpc: '2.0', id: id, error: { code: code, message: message } }) + '\n',
  )
}

async function handleLine(line) {
  let message = null
  try {
    message = JSON.parse(line)
  } catch (error) {
    return
  }
  if (!message || typeof message !== 'object') return
  const id = message.id
  const method = message.method
  const params = message.params && typeof message.params === 'object' ? message.params : {}
  try {
    if (method === 'plugin.activate') return reply(id, await activate(params))
    if (method === 'plugin.session') return reply(id, resolveSession(params))
    if (method === 'plugin.request') return reply(id, await request(params))
    if (method === 'plugin.deactivate') return reply(id, { ok: true })
    return replyError(id, 400, 'unknown method ' + String(method))
  } catch (error) {
    return replyError(id, 500, error instanceof Error ? error.message : String(error))
  }
}

function resolveSession() {
  return null
}

let buffer = ''
// Lines are handled one at a time: a request must never overtake the activate
// that sets up state, and replies must leave in the order they were produced.
let queue = Promise.resolve()
process.stdin.setEncoding('utf8')
process.stdin.on('data', (chunk) => {
  buffer += chunk
  let index = buffer.indexOf('\n')
  while (index >= 0) {
    const line = buffer.slice(0, index).trim()
    buffer = buffer.slice(index + 1)
    if (line) queue = queue.then(() => handleLine(line))
    index = buffer.indexOf('\n')
  }
})
// Set the exit code instead of calling process.exit(): stdout is a pipe here, and
// exiting early drops replies that have not been flushed yet.
process.stdin.on('end', () => {
  queue.then(() => {
    process.exitCode = 0
  })
})
`

const HTTP_ENTRY =
  String.raw`#!/usr/bin/env node
/**
 * Pilot plugin entry — generated by the plugin assistant.
 * Keep stdout for protocol replies only: a stray console.log corrupts the
 * JSON-RPC stream the host reads.
 */
import { appendFile, mkdir } from 'node:fs/promises'
import { join } from 'node:path'

let stateDir = '.'
let readyAt = null
const items = []

async function activate(params) {
  const dir = params && typeof params.stateDir === 'string' ? params.stateDir : ''
  if (dir) stateDir = dir
  await mkdir(stateDir, { recursive: true })
  readyAt = new Date().toISOString()
  return { ok: true, api: params.api, plugin: params.plugin && params.plugin.id }
}

async function request(params) {
  const route = params && params.route && typeof params.route === 'object' ? params.route : {}
  const body = params && params.body && typeof params.body === 'object' ? params.body : {}
  if (route.path === 'health') {
    return { status: 200, body: { ok: true, readyAt: readyAt, items: items.length } }
  }
  if (route.path === 'items' && route.method === 'GET') {
    return { status: 200, body: { items: items } }
  }
  if (route.path === 'items' && route.method === 'POST') {
    const title = typeof body.title === 'string' ? body.title.trim() : ''
    if (!title) return { status: 400, body: { error: 'title is required' } }
    const item = { id: items.length + 1, title: title, at: new Date().toISOString() }
    items.push(item)
    await appendFile(join(stateDir, 'items.jsonl'), JSON.stringify(item) + '\n', 'utf8')
    return { status: 201, body: item }
  }
  return { status: 404, body: { error: 'unknown route ' + String(route.method) + ' ' + String(route.path) } }
}
` + PROTOCOL_HELPERS

const SESSION_ENTRY =
  String.raw`#!/usr/bin/env node
/**
 * Pilot session provider — generated by the plugin assistant.
 * Replace signIn() with your staff directory or SSO lookup; the host only
 * cares that plugin.session resolves a token into a session object.
 */
import { randomUUID } from 'node:crypto'

const sessions = new Map()

async function activate(params) {
  return { ok: true, api: params.api, plugin: params.plugin && params.plugin.id }
}

function signIn(name) {
  const token = randomUUID()
  sessions.set(token, {
    subject: name,
    roles: ['member'],
    permissions: [],
    expiresAt: new Date(Date.now() + 12 * 60 * 60 * 1000).toISOString(),
    profile: { name: name },
  })
  return token
}

async function request(params) {
  const route = params && params.route && typeof params.route === 'object' ? params.route : {}
  const body = params && params.body && typeof params.body === 'object' ? params.body : {}
  if (route.path === 'login' && route.method === 'POST') {
    const name = typeof body.name === 'string' ? body.name.trim() : ''
    if (!name) return { status: 400, body: { error: 'name is required' } }
    return { status: 201, body: { token: signIn(name) } }
  }
  if (route.path === 'me' && route.method === 'GET') {
    const session = sessions.get(params.token) || null
    if (!session) return { status: 401, body: { error: 'unknown token' } }
    return { status: 200, body: session }
  }
  return { status: 404, body: { error: 'unknown route ' + String(route.method) + ' ' + String(route.path) } }
}

function resolveSession(params) {
  return sessions.get(params && params.token) || null
}
` + PROTOCOL_HELPERS.replace(
    'function resolveSession() {\n  return null\n}\n\n',
    '',
  )

const WEBHOOK_ENTRY =
  String.raw`#!/usr/bin/env node
/**
 * Pilot event sink — generated by the plugin assistant.
 * Events are appended to <stateDir>/events.jsonl so a restart loses nothing.
 * Swap appendEvent() for your queue or upstream HTTP call.
 */
import { appendFile, mkdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'

let stateDir = '.'
let readyAt = null

async function activate(params) {
  const dir = params && typeof params.stateDir === 'string' ? params.stateDir : ''
  if (dir) stateDir = dir
  await mkdir(stateDir, { recursive: true })
  readyAt = new Date().toISOString()
  return { ok: true, api: params.api, plugin: params.plugin && params.plugin.id }
}

async function readEvents() {
  try {
    const raw = await readFile(join(stateDir, 'events.jsonl'), 'utf8')
    return raw
      .split('\n')
      .filter((line) => line.trim())
      .slice(-20)
      .map((line) => {
        try {
          return JSON.parse(line)
        } catch (error) {
          return { raw: line }
        }
      })
  } catch (error) {
    return []
  }
}

async function request(params) {
  const route = params && params.route && typeof params.route === 'object' ? params.route : {}
  const body = params && params.body && typeof params.body === 'object' ? params.body : {}
  if (route.path === 'events' && route.method === 'POST') {
    const type = typeof body.type === 'string' ? body.type.trim() : ''
    if (!type) return { status: 400, body: { error: 'type is required' } }
    const event = { type: type, payload: body.payload || null, at: new Date().toISOString() }
    await appendFile(join(stateDir, 'events.jsonl'), JSON.stringify(event) + '\n', 'utf8')
    return { status: 202, body: { accepted: true, at: event.at } }
  }
  if (route.path === 'events' && route.method === 'GET') {
    return { status: 200, body: { readyAt: readyAt, events: await readEvents() } }
  }
  return { status: 404, body: { error: 'unknown route ' + String(route.method) + ' ' + String(route.path) } }
}
` + PROTOCOL_HELPERS

